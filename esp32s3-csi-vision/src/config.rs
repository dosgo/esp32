//! 全部可调参数集中在这里。
//!
//! Wi-Fi 账号密码**不在这里**——现在通过热点配网写进 flash，
//! 连上 `CSI-Vision` 打开 `http://192.168.4.1/setup` 填就行，不用改代码重烧。

// ============================================================
//  热点（AP）：永远开着，配网和救急都靠它
// ============================================================

pub const AP_SSID: &str = "CSI-Vision";
/// 热点密码，至少 8 位；留空 = 开放网络。
pub const AP_PASS: &str = "csi12345";
/// 热点下 ESP32 自己的地址（配网页就是 http://192.168.4.1/setup）。
pub const AP_IP: [u8; 4] = [192, 168, 4, 1];

// ============================================================
//  STA（连家里的 2.4G 路由）
// ============================================================

/// 单次连接超时。家用路由器正常 2~5 秒就关联上了，
/// 给 20 秒是为了容忍信号差时的重试。
pub const STA_TIMEOUT_SECS: u64 = 20;

/// 连接失败后隔多久重试。
pub const STA_RETRY_SECS: u64 = 15;

// ============================================================
//  CSI 采集参数
// ============================================================

/// 自发 ping 的间隔（毫秒）。CSI 只在「收到包」时上报，
/// 所以必须有稳定的下行流量。ping 网关是最自包含的办法。
///
/// - 10ms = 100Hz 采样，动作识别足够，路由器基本不限速
/// - 想更细可以到 5ms，但很多家用路由器会开始丢 ICMP
/// - 别低于 4ms：ESP32 的 ICMP 回包跟不上，反而变慢
pub const PING_INTERVAL_MS: u64 = 10;

/// 推给浏览器的帧间隔（毫秒）。
///
/// CSI 回调本身有 100~300Hz，全推给浏览器的话瀑布图重绘会吃掉大量 CPU，
/// 而人眼 50fps 以上看不出差别。20ms = 50fps 是画质和开销的平衡点。
pub const PUSH_MS: u32 = 20;

// ============================================================
//  Web 服务
// ============================================================

pub const HTTP_PORT: u16 = 80;

/// 一次 HTTP 连接的 socket 缓冲（每个方向）。页面约 20KB，
/// 写的时候分块循环，所以不到 2KB 也够。
pub const WEB_BUF: usize = 1792;

/// 同时支持的网页连接数（每个 stack）。
///
/// **必须给够**：手机浏览器打开一个页面会同时发起好几个连接
/// （主页、favicon、预连接），而且关掉标签页时对端往往不发 FIN，
/// 那条连接要等超时才释放。槽位少了，新连接直接被 RST ——
/// 现象就是「网页突然打不开了，但板子还在跑」。
///
/// 6 个：1 个 WebSocket 看成像 + 1 个配网页轮询 + 4 个给浏览器的并发/僵尸连接。
///
/// 压测教训：开 3 个 WS 会话后，HTTP 请求开始被 RST 拒绝（WinError 10061）。
/// 5 个槽在「多个页面 + 浏览器预连接」的场景下余量不够。
pub const WEB_SESSIONS: usize = 6;
